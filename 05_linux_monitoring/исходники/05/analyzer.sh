#!/bin/bash

# Режим 1: выводит все строки, сортируя их по числовому коду ответа.
# В Combined Log Format код ответа находится в девятом поле.
print_sorted_by_code() {
    awk '{ print }' "$@" | LC_ALL=C sort -s -k9,9n
}

# Режим 2: выводит каждый IP-адрес только при первом появлении.
print_unique_ips() {
    awk '!seen[$1]++ { print $1 }' "$@"
}

# Режим 3: выводит запросы с клиентскими и серверными ошибками.
# Регулярное выражение принимает коды от 400 до 599.
print_error_requests() {
    awk '$9 ~ /^[45][0-9][0-9]$/ { print }' "$@"
}

# Режим 4: выводит уникальные IP только из ошибочных запросов.
print_unique_error_ips() {
    awk '$9 ~ /^[45][0-9][0-9]$/ && !seen[$1]++ { print $1 }' "$@"
}
