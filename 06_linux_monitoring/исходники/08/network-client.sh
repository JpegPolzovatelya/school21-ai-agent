#!/bin/bash

# Скрипт принимает IPv4-адрес второй виртуальной машины.
if [[ $# -ne 1 ]]; then
    echo "Использование: $0 IP_ВТОРОЙ_ВМ" >&2
    exit 1
fi

server_ip="$1"

if [[ ! "$server_ip" =~ ^([0-9]{1,3}\.){3}[0-9]{1,3}$ ]]; then
    echo "Ошибка: указан некорректный формат IPv4." >&2
    exit 1
fi

IFS=. read -r -a octets <<< "$server_ip"
for octet in "${octets[@]}"; do
    if (( 10#$octet > 255 )); then
        echo "Ошибка: октеты IPv4 должны быть от 0 до 255." >&2
        exit 1
    fi
done

# Четыре параллельных потока передают данные в течение 30 секунд.
echo "Тест исходящего трафика..."
iperf3 -c "$server_ip" -t 30 -P 4

# Флаг -R меняет направление: вторая ВМ передаёт данные первой.
echo "Тест входящего трафика..."
iperf3 -c "$server_ip" -t 30 -P 4 -R
